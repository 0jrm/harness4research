#!/usr/bin/env python3
"""usage: tools/plan-status.py [--plan PATH] [--out PATH] [--notes PATH] [--baseline PATH]
Writes docs/status.md from the records, so a hand edit to it is overwritten: each item id in the plan's Workstreams
table with the pull requests whose titles start with "[<id>]" (one gh pr list call), the audit's counts from
eval/audit/baseline.json, the open needs-you items, and docs/status-notes.md, the one hand-written part, appended
as it is. The plan defaults to the newest docs/plan-*.md. Run it before each hand-off. Exit 2 when gh cannot list."""
import glob
import json
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def arg(name, default):
    args = sys.argv[1:]
    return args[args.index(name) + 1] if name in args else default


def plan_items(path):
    """The (id, change) rows of the plan's Workstreams table, in order."""
    with open(path) as f:
        text = f.read()
    section = text.split("## Workstreams", 1)[1].split("\n## ", 1)[0]
    items = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and re.fullmatch(r"W[0-9][0-9.\-]*", cells[0]):
            items.append((cells[0], cells[1]))
    return items


def pull_requests():
    try:
        out = subprocess.run(["gh", "pr", "list", "--state", "all", "--limit", "1000", "--json", "number,title,state"],
                             capture_output=True, text=True)
        why = out.stderr.strip() if out.returncode else ""
    except FileNotFoundError:
        why = "gh is not on PATH"
    if why:
        print(f"plan-status: gh cannot list pull requests: {why}", file=sys.stderr)
        sys.exit(2)
    return json.loads(out.stdout or "[]")


def state_of(item, prs):
    mine = sorted((p for p in prs if p["title"].startswith(f"[{item}]")), key=lambda p: p["number"])
    if not mine:
        return "not started"
    words = {"MERGED": "merged", "OPEN": "open", "CLOSED": "closed"}
    return ", ".join(f"{words.get(p['state'], p['state'].lower())} #{p['number']}" for p in mine)


def audit(path):
    if not os.path.exists(path):
        return "no baseline yet"
    with open(path) as f:
        verdicts = list(json.load(f).values())
    return (f"{verdicts.count('HELD')} held, {verdicts.count('BYPASSED')} bypassed of {len(verdicts)} rows, "
            f"from `eval/audit/baseline.json`.")


def queue():
    out = subprocess.run([os.path.join(REPO, "bin", "guard"), "needs-you", "--remind"], capture_output=True, text=True)
    rows = [line.strip() for line in out.stdout.splitlines() if re.match(r"\s+n[0-9]+ · ", line)]
    return [f"- {row}" for row in rows] or ["- nothing open"]


def main():
    if "--help" in sys.argv or "-h" in sys.argv:
        print(__doc__)
        return
    plans = sorted(glob.glob(os.path.join(REPO, "docs", "plan-*.md")))
    plan = arg("--plan", plans[-1] if plans else "")
    out = arg("--out", os.path.join(REPO, "docs", "status.md"))
    notes = arg("--notes", os.path.join(REPO, "docs", "status-notes.md"))
    baseline = arg("--baseline", os.path.join(REPO, "eval", "audit", "baseline.json"))
    prs = pull_requests()
    name = os.path.basename(plan)
    lines = ["# Status", "",
             f"Generated by `tools/plan-status.py`; edit [status-notes.md](status-notes.md) instead, since this page "
             f"is rewritten. The plan is [{name}]({name}).", "",
             "## Plan items", "", "| item | change | pull requests |", "|---|---|---|"]
    for item, change in plan_items(plan):
        change = change.replace("`", "")
        short = change if len(change) <= 48 else change[:45].rsplit(" ", 1)[0] + " ..."
        lines.append(f"| {item} | {short} | {state_of(item, prs)} |")
    lines += ["", "## Audit", "", audit(baseline), "", "## The owner's queue", ""] + queue()
    if os.path.exists(notes):
        with open(notes) as f:
            lines += ["", f.read().rstrip()]
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"plan-status: wrote {os.path.relpath(out, os.getcwd())}")


if __name__ == "__main__":
    main()
